"""Build small UI subsets from the vendored variable fonts, retaining full fallbacks.

Manual maintenance: install scripts/font-tools-requirements.txt, then run this file.
Neither production builds nor visitors need Python or external font services.
"""

from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps/web"
PUBLIC = WEB / "public"
MANIFEST = PUBLIC / "fonts/manifest.json"


def codepoints(ranges):
    result = set()
    for item in ranges.split(","):
        bounds = item.strip().upper().removeprefix("U+").split("-")
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        result.update(range(start, end + 1))
    return result


def unicode_range(points):
    ordered = sorted(points)
    groups = []
    for point in ordered:
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in groups
    )


def face(font, ranges):
    return (
        "@font-face {\n"
        f"  font-family: '{font['family']}';\n"
        "  font-style: normal;\n"
        f"  font-weight: {font['weight']};\n"
        "  font-display: swap;\n"
        f"  src: url({font['file']}) format('woff2');\n"
        f"  unicode-range: {unicode_range(ranges)};\n"
        "}\n"
    )


def main():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    characters = set(range(0x20, 0x7F))
    for source in sorted((WEB / "app").rglob("*")):
        if source.suffix in (".vue", ".ts"):
            characters.update(map(ord, source.read_text(encoding="utf-8")))

    originals = manifest["fonts"]
    small_fonts = []
    family_ui = {}
    actual_coverage = {}
    # Retain DM Sans unchanged: its existing small Latin subsets are inexpensive.
    for index, original in enumerate(originals):
        if original["family"] == "DM Sans":
            continue
        source = PUBLIC / original["file"].lstrip("/")
        with TTFont(source, recalcTimestamp=False) as font:
            original_coverage = set(font.getBestCmap()) & codepoints(original["range"])
            actual_coverage[original["file"]] = original_coverage
            selected = original_coverage & characters
            if not selected:
                continue
            axes = [(axis.axisTag, axis.minValue, axis.maxValue) for axis in font["fvar"].axes] if "fvar" in font else []
            options = subset.Options()
            options.layout_features = ["*"]
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=selected)
            subsetter.subset(font)
            buffer = BytesIO()
            font.save(buffer, reorderTables=True)
            data = buffer.getvalue()
        digest = sha256(data).hexdigest()
        url = f"/fonts/generated/{original['key']}-ui-{digest[:16]}.woff2"
        output = PUBLIC / url.lstrip("/")
        output.write_bytes(data)
        with TTFont(output) as verified:
            assert selected <= set(verified.getBestCmap()), "UI glyphs lost during subsetting"
            assert axes == ([(axis.axisTag, axis.minValue, axis.maxValue) for axis in verified["fvar"].axes] if "fvar" in verified else []), "Variable font axes changed"
        small_fonts.append({
            "family": original["family"], "key": original["key"],
            "weight": original["weight"], "file": url,
            "range": unicode_range(selected), "bytes": len(data),
            "sha256": digest, "original": original["file"],
        })
        family_ui.setdefault(original["family"], set()).update(selected)
        if index % 25 == 0:
            print(f"Subsetting font {index + 1}/{len(originals)}", flush=True)

    css = ["/* Generated by vendor-fonts.mjs + subset-ui-fonts.py. Original fonts cover every non-UI character; licenses: /fonts/LICENSES.txt. */\n"]
    for original in originals:
        remaining = codepoints(original["range"]) - family_ui.get(original["family"], set())
        if remaining:
            css.append(face(original, remaining))
        if original["family"] in family_ui:
            # Every previously available code point still belongs to a UI face or its original fallback.
            assert actual_coverage[original["file"]] <= remaining | family_ui[original["family"]]
    for font in small_fonts:
        css.append(face(font, codepoints(font["range"])))
    (WEB / "app/assets/css/fonts.css").write_text("\n".join(css), encoding="utf-8", newline="\n")
    manifest["version"] = 2
    manifest["ui"] = {
        "charactersSha256": sha256("".join(map(chr, sorted(characters))).encode()).hexdigest(),
        "fonts": small_fonts,
    }
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(small_fonts)} small UI fonts; original variable fonts and Unicode coverage retained.")


if __name__ == "__main__":
    main()
